/**
 * Get the URL for an icon library by ID or prefix
 * Falls back to Iconify's collection page for libraries not in our list
 */
export function getIconLibraryUrl(idOrPrefix: string): string {
  const library = ICON_LIBRARY_URLS[idOrPrefix.toLowerCase()];
  // Fallback to Iconify's collection page for any library
  return library?.url || `https://icon-sets.iconify.design/${idOrPrefix.toLowerCase()}/`;
}

/**
 * Get icon library info by ID or prefix
 * Returns curated info if available, otherwise generates from ID
 */
export function getIconLibraryInfo(idOrPrefix: string): { name: string; url: string } {
  const id = idOrPrefix.toLowerCase();
  const library = ICON_LIBRARY_URLS[id];

  if (library) {
    return library;
  }

  // Generate a readable name from the ID (e.g., "my-icons" -> "My Icons")
  const name = id
    .split(/[-_]/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");

  return {
    name,
    url: `https://icon-sets.iconify.design/${id}/`,
  };
}

/**
 * Get all icon library names for pattern matching in text
 */
export function getIconLibraryNames(): string[] {
  return Object.values(ICON_LIBRARY_URLS).map((lib) => lib.name);
}

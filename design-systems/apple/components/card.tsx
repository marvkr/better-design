  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[18px] bg-card text-card-foreground",
      "shadow-[2px_4px_12px_rgba(0,0,0,0.08)]",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

